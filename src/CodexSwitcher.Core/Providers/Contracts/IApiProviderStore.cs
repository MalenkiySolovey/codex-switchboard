    void SaveAll(IEnumerable<ApiProviderProfile> profiles, ApiProviderSaveIntent intent = ApiProviderSaveIntent.NormalUpdate);
    bool Delete(Guid id);
    bool SetStatus(Guid id, ApiProviderProfileStatus status);
}
